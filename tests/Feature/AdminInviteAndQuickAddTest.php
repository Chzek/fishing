<?php

namespace Tests\Feature;

use Fishinglog\Models\Angler;
use Fishinglog\Models\User;
use Illuminate\Foundation\Testing\DatabaseTransactions;
use Illuminate\Support\Facades\Hash;
use Illuminate\Support\Facades\URL;
use PHPUnit\Framework\Attributes\Test;
use Tests\TestCase;

class AdminInviteAndQuickAddTest extends TestCase
{
    use DatabaseTransactions;

    #[Test]
    public function public_register_route_is_disabled()
    {
        $response = $this->get('/register');
        $response->assertStatus(404);
    }

    #[Test]
    public function admin_can_generate_signed_invite_link_and_invited_user_can_register()
    {
        $admin = User::factory()->create(['type' => User::ADMIN_TYPE]);

        // 1. Admin generates invite
        $inviteResponse = $this->actingAs($admin)->post('/admin/users/invite', [
            'name' => 'Invited Angler',
            'email' => 'invited@example.com',
        ]);

        $inviteResponse->assertRedirect(route('admin.users'));
        $inviteResponse->assertSessionHas('status');
        $inviteResponse->assertSessionHas('invite_url');

        // 2. Generate valid relative signed URL
        $relativeSignedPath = URL::temporarySignedRoute(
            'register.invited',
            now()->addDays(7),
            ['email' => 'invited@example.com', 'name' => 'Invited Angler'],
            false
        );

        $getFormResponse = $this->get($relativeSignedPath);
        $getFormResponse->assertStatus(200);
        $getFormResponse->assertSee('Complete Account Setup');

        // 3. Complete invited registration
        $postResponse = $this->post($relativeSignedPath, [
            'name' => 'Invited Angler',
            'email' => 'invited@example.com',
            'password' => 'secret12345',
            'password_confirmation' => 'secret12345',
        ]);

        $postResponse->assertRedirect(route('home'));
        $this->assertDatabaseHas('users', ['email' => 'invited@example.com']);
        $this->assertDatabaseMissing('anglers', ['firstName' => 'Invited Angler']);
        $this->assertCount(1, $admin->fresh()->notifications);
    }

    #[Test]
    public function signed_invite_link_works_across_different_schemes_and_hostnames()
    {
        // 1. Generate relative signed path (as generated by laptop)
        $relativeSignedPath = URL::temporarySignedRoute(
            'register.invited',
            now()->addDays(7),
            ['email' => 'wife@example.com', 'name' => 'Jane Doe'],
            false
        );

        // 2. Access via production HTTPS NAS hostname
        $nasUrl = 'https://fishinglog.chzek-safe.synology.me' . $relativeSignedPath;
        $response = $this->get($nasUrl);
        $response->assertStatus(200);
        $response->assertSee('Complete Account Setup');
        $response->assertSee('wife@example.com');

        // 3. Complete registration via production URL
        $registerResponse = $this->post($nasUrl, [
            'name' => 'Jane Doe',
            'email' => 'wife@example.com',
            'password' => 'securepass123',
            'password_confirmation' => 'securepass123',
        ]);

        $registerResponse->assertRedirect(route('home'));
        $this->assertDatabaseHas('users', ['email' => 'wife@example.com', 'name' => 'Jane Doe']);
    }

    #[Test]
    public function tampered_or_invalid_signature_is_rejected_with_403()
    {
        $tamperedUrl = '/register/invited?email=hacker@example.com&name=Hacker&expires=9999999999&signature=invalid_hash';
        $response = $this->get($tamperedUrl);
        $response->assertStatus(403);
    }

    #[Test]
    public function admin_can_create_angler_account_via_canada_offline_quick_add()
    {
        $admin = User::factory()->create(['type' => User::ADMIN_TYPE]);

        $response = $this->actingAs($admin)->post('/admin/users/quick-add', [
            'name' => 'Canada Angler',
            'email' => 'canada@example.com',
            'password' => 'fieldpass123',
        ]);

        $response->assertRedirect(route('admin.users'));
        $response->assertSessionHas('status');

        $user = User::where('email', 'canada@example.com')->first();
        $this->assertNotNull($user);
        $this->assertEquals('pending_upstream', $user->sync_status);
        $this->assertNotEmpty($user->id);

        $angler = Angler::where('user_id', $user->id)->first();
        $this->assertNotNull($angler);
        $this->assertEquals('Canada', $angler->firstName);
        $this->assertEquals('pending_upstream', $angler->sync_status);
    }

    #[Test]
    public function admin_can_generate_temporary_password_for_user()
    {
        $admin = User::factory()->create(['type' => User::ADMIN_TYPE]);
        $targetUser = User::factory()->create([
            'password' => Hash::make('prior-password'),
        ]);

        $response = $this->actingAs($admin)->post(route('admin.users.reset-password', $targetUser), [
            'action' => 'temporary_password',
        ]);

        $response->assertRedirect(route('admin.users'));
        $response->assertSessionHas('temp_password');
        $tempPassword = session('temp_password');
        $this->assertNotEmpty($tempPassword);

        $this->assertTrue(Hash::check($tempPassword, $targetUser->fresh()->password));
    }

    #[Test]
    public function admin_can_generate_instant_reset_link_for_user()
    {
        $admin = User::factory()->create(['type' => User::ADMIN_TYPE]);
        $targetUser = User::factory()->create();

        $response = $this->actingAs($admin)->post(route('admin.users.reset-password', $targetUser), [
            'action' => 'reset_link',
        ]);

        $response->assertRedirect(route('admin.users'));
        $response->assertSessionHas('reset_url');
        $resetUrl = session('reset_url');
        $this->assertNotEmpty($resetUrl);
        $this->assertStringContainsString('password/reset/', $resetUrl);
    }

    #[Test]
    public function non_admin_cannot_reset_passwords()
    {
        $user = User::factory()->create(['type' => User::DEFAULT_TYPE]);
        $targetUser = User::factory()->create();

        $response = $this->actingAs($user)->post(route('admin.users.reset-password', $targetUser), [
            'action' => 'temporary_password',
        ]);

        $response->assertRedirect('/home');
    }
}
